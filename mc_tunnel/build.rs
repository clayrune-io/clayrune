//
// Inputs (set by the release pipeline, NEVER committed to source):
//   CLIENT_SECRET_KEY_ID   — e.g. "mc-tunnel-2026a"
//   CLIENT_SECRET_PRIV_HEX — 64 hex chars (32 bytes) of Ed25519 private key seed
//
// Both or neither. Neither = a dev build (placeholder id, zero seed,
// IS_DEV_BUILD = true; main.rs refuses to run it). Exactly one is a build
// error: a key id without a key would otherwise sign with 32 zero bytes
// while claiming to be a release.
//
// Output: $OUT_DIR/client_secret.rs, pulled in by main.rs with include!().
// $OUT_DIR lives under target/ (ignored), so the key never lands in a tracked
// file or in the working tree outside the build directory.
//
// See `05-build-pipeline.md` §3.1 for the operator workflow.

use std::env;
use std::fs;
use std::path::Path;

const DEV_KEY_ID: &str = "DEV-NOT-FOR-RELEASE";

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=CLIENT_SECRET_KEY_ID");
    println!("cargo:rerun-if-env-changed=CLIENT_SECRET_PRIV_HEX");

    // An empty value counts as unset (a pipeline template with an empty secret).
    let key_id = env::var("CLIENT_SECRET_KEY_ID").ok().filter(|v| !v.is_empty());
    let priv_hex = env::var("CLIENT_SECRET_PRIV_HEX").ok().filter(|v| !v.is_empty());

    let (key_id, priv_hex, is_dev) = match (key_id, priv_hex) {
        (Some(id), Some(hex)) => (id, hex, false),
        // Fallback for `cargo check` / IDE integration. Builds will refuse to
        // run if the real env vars aren't set — see main.rs runtime check.
        (None, None) => (DEV_KEY_ID.to_string(), "00".repeat(32), true),
        (Some(_), None) => panic!(
            "CLIENT_SECRET_KEY_ID is set but CLIENT_SECRET_PRIV_HEX is not; set both or neither"
        ),
        (None, Some(_)) => panic!(
            "CLIENT_SECRET_PRIV_HEX is set but CLIENT_SECRET_KEY_ID is not; set both or neither"
        ),
    };

    if priv_hex.len() != 64 || !priv_hex.bytes().all(|b| b.is_ascii_hexdigit()) {
        // Length only: never echo the value, it is the private key.
        panic!("CLIENT_SECRET_PRIV_HEX must be 64 hex chars; got {} chars", priv_hex.len());
    }

    let mut bytes = [0u8; 32];
    for i in 0..32 {
        bytes[i] = u8::from_str_radix(&priv_hex[i * 2..i * 2 + 2], 16)
            .expect("CLIENT_SECRET_PRIV_HEX must be valid hex");
    }

    let mut byte_literals = String::with_capacity(32 * 6);
    for (i, b) in bytes.iter().enumerate() {
        if i > 0 { byte_literals.push_str(", "); }
        byte_literals.push_str(&format!("0x{:02x}", b));
    }

    let generated = format!(
        "// AUTO-GENERATED by build.rs into OUT_DIR — DO NOT EDIT.\n\
         pub const CLIENT_SECRET_KEY_ID: &str = {key_id:?};\n\
         pub const CLIENT_SECRET_PRIV: [u8; 32] = [{byte_literals}];\n\
         pub const IS_DEV_BUILD: bool = {is_dev};\n",
        key_id = key_id,
        byte_literals = byte_literals,
        is_dev = is_dev,
    );

    let out_dir = env::var("OUT_DIR").expect("cargo sets OUT_DIR for build scripts");
    let out = Path::new(&out_dir).join("client_secret.rs");
    fs::write(&out, generated).expect("could not write client_secret.rs to OUT_DIR");
}
